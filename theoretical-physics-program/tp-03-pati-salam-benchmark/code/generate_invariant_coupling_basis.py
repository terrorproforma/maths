#!/usr/bin/env python3
"""Generate a canonical abstract coupling-channel basis for all TP-03 scalar invariants.

This refines the Molien--Weyl count into an explicit *representation-channel* basis.
For each nonzero multidegree, every invariant is labelled by a fixed left-associated
coupling path through irreducible representations of
SU(4)_C x SU(2)_L x SU(2)_R.

The output is a complete basis of Hom_G(1, tensor_X Sym^{n_X} R_X) once a
standard orthonormal Clebsch--Gordan map is chosen for each labelled channel.
It deliberately does not print enormous component tensors; phase conventions for
CG coefficients are conventional and do not change independence or completeness.

All decompositions use exact integer weight characters. SU(4) Weyl characters are
generated by Gelfand--Tsetlin patterns; SU(2) characters are elementary.
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from functools import lru_cache
from pathlib import Path
from typing import Dict, Iterable, List, Mapping, Sequence, Tuple

from count_scalar_invariants import (
    FIELD_NAMES,
    SYMMETRIC_CHARACTERS,
    ZERO,
    Weight,
    Poly,
    add_weight,
    compute_counts,
    multiply_poly,
)

Irrep = Tuple[int, int, int, int, int]  # SU4 Dynkin (a,b,c), SU2L highest weight, SU2R highest weight
SINGLET: Irrep = (0, 0, 0, 0, 0)


def su4_partition(dynkin: Tuple[int, int, int]) -> Tuple[int, int, int, int]:
    a, b, c = dynkin
    if min(dynkin) < 0:
        raise ValueError(f"negative Dynkin label {dynkin}")
    return (a + b + c, b + c, c, 0)


@lru_cache(maxsize=None)
def su4_character(dynkin: Tuple[int, int, int]) -> Dict[Tuple[int, int, int], int]:
    """SU(4) character in z1,z2,z3 with z4=(z1 z2 z3)^(-1)."""
    l1, l2, l3, l4 = su4_partition(dynkin)
    out: defaultdict[Tuple[int, int, int], int] = defaultdict(int)

    # Gelfand--Tsetlin interlacing pattern:
    # l1 l2 l3 l4
    #   m1 m2 m3
    #     n1 n2
    #       p1
    for m1 in range(l2, l1 + 1):
        for m2 in range(l3, l2 + 1):
            for m3 in range(l4, l3 + 1):
                sum_m = m1 + m2 + m3
                for n1 in range(m2, m1 + 1):
                    for n2 in range(m3, m2 + 1):
                        sum_n = n1 + n2
                        for p1 in range(n2, n1 + 1):
                            # GL(4) content weights are differences of row sums.
                            w1 = p1
                            w2 = sum_n - p1
                            w3 = sum_m - sum_n
                            w4 = (l1 + l2 + l3 + l4) - sum_m
                            out[(w1 - w4, w2 - w4, w3 - w4)] += 1
    return dict(out)


@lru_cache(maxsize=None)
def su2_character(highest: int) -> Dict[int, int]:
    if highest < 0:
        raise ValueError("negative SU(2) highest weight")
    return {weight: 1 for weight in range(highest, -highest - 1, -2)}


@lru_cache(maxsize=None)
def irrep_character(label: Irrep) -> Poly:
    a, b, c, left, right = label
    out: Poly = {}
    for su4_weight, c4 in su4_character((a, b, c)).items():
        for wl, cl in su2_character(left).items():
            for wr, cr in su2_character(right).items():
                out[su4_weight + (wl, wr)] = c4 * cl * cr
    return out


def canonical_highest_weight(label: Irrep) -> Weight:
    a, b, c, left, right = label
    partition = su4_partition((a, b, c))
    return (partition[0], partition[1], partition[2], left, right)


def dominant_irrep(weight: Weight) -> Irrep:
    x1, x2, x3, left, right = weight
    exponents = sorted((x1, x2, x3, 0), reverse=True)
    base = exponents[-1]
    partition = tuple(value - base for value in exponents)
    a = partition[0] - partition[1]
    b = partition[1] - partition[2]
    c = partition[2] - partition[3]
    return (a, b, c, abs(left), abs(right))


def weight_norm_sq(weight: Weight) -> int:
    """Positive Weyl-invariant norm, scaled to remain integer."""
    x1, x2, x3, left, right = weight
    e = (x1, x2, x3, 0)
    # 4 * sum_i (e_i - mean(e))^2 = 4 sum e_i^2 - (sum e_i)^2.
    su4 = 4 * sum(value * value for value in e) - sum(e) ** 2
    return su4 + 2 * left * left + 2 * right * right


def clean(poly: Mapping[Weight, int]) -> Poly:
    return {weight: coefficient for weight, coefficient in poly.items() if coefficient}


@lru_cache(maxsize=None)
def decompose_character_cached(items: Tuple[Tuple[Weight, int], ...]) -> Tuple[Tuple[Irrep, int], ...]:
    residual: Dict[Weight, int] = dict(items)
    result: defaultdict[Irrep, int] = defaultdict(int)

    while residual:
        if min(residual.values()) < 0:
            negative = min(residual.items(), key=lambda item: item[1])
            raise ArithmeticError(f"negative residual before decomposition: {negative}")
        probe = max(residual, key=lambda weight: (weight_norm_sq(weight), weight))
        label = dominant_irrep(probe)
        highest = canonical_highest_weight(label)
        multiplicity = residual.get(highest, 0)
        if multiplicity <= 0:
            raise ArithmeticError(
                f"dominant orbit {label} selected from {probe}, but canonical highest {highest} "
                f"has multiplicity {multiplicity}"
            )
        result[label] += multiplicity
        character = irrep_character(label)
        for weight, coefficient in character.items():
            new_value = residual.get(weight, 0) - multiplicity * coefficient
            if new_value < 0:
                raise ArithmeticError(
                    f"negative residual subtracting {multiplicity}*{label} at {weight}: {new_value}"
                )
            if new_value:
                residual[weight] = new_value
            else:
                residual.pop(weight, None)
    return tuple(sorted(result.items()))


def decompose_character(character: Mapping[Weight, int]) -> List[Tuple[Irrep, int]]:
    return list(decompose_character_cached(tuple(sorted(clean(character).items()))))


@lru_cache(maxsize=None)
def tensor_decomposition(left: Irrep, right: Irrep) -> Tuple[Tuple[Irrep, int], ...]:
    character = multiply_poly(irrep_character(left), irrep_character(right))
    return tuple(decompose_character(character))


def label_text(label: Irrep) -> str:
    return f"[{label[0]},{label[1]},{label[2]}];{label[3]};{label[4]}"


def symmetric_power_decompositions() -> Dict[str, Dict[int, List[Tuple[Irrep, int]]]]:
    out: Dict[str, Dict[int, List[Tuple[Irrep, int]]]] = {}
    for field in FIELD_NAMES:
        out[field] = {}
        for degree in range(5):
            out[field][degree] = decompose_character(SYMMETRIC_CHARACTERS[field][degree])
    return out


def build_basis() -> Dict[str, object]:
    count_result = compute_counts()
    factor_decompositions = symmetric_power_decompositions()
    channels: List[Dict[str, object]] = []
    counts_by_multidegree: Dict[Tuple[int, ...], int] = {}

    for row in count_result["rows"]:  # type: ignore[index]
        assert isinstance(row, dict)
        exponents = tuple(int(value) for value in row["multidegree"])  # type: ignore[index]
        expected = int(row["singlet_multiplicity"])

        # Each path is carried separately; copy indices make multiplicity spaces explicit.
        paths: List[Tuple[Irrep, List[Dict[str, object]]]] = [(SINGLET, [])]
        for field, degree in zip(FIELD_NAMES, exponents):
            if degree == 0:
                continue
            next_paths: List[Tuple[Irrep, List[Dict[str, object]]]] = []
            for current_label, history in paths:
                for factor_label, factor_multiplicity in factor_decompositions[field][degree]:
                    for factor_copy in range(1, factor_multiplicity + 1):
                        for output_label, cg_multiplicity in tensor_decomposition(current_label, factor_label):
                            for cg_copy in range(1, cg_multiplicity + 1):
                                step = {
                                    "field": field,
                                    "symmetric_degree": degree,
                                    "factor_irrep": list(factor_label),
                                    "factor_copy": factor_copy,
                                    "input_irrep": list(current_label),
                                    "output_irrep": list(output_label),
                                    "cg_copy": cg_copy,
                                }
                                next_paths.append((output_label, history + [step]))
            paths = next_paths

        singlet_paths = [history for label, history in paths if label == SINGLET]
        if len(singlet_paths) != expected:
            raise ArithmeticError(
                f"basis count mismatch for {exponents}: got {len(singlet_paths)}, expected {expected}"
            )
        counts_by_multidegree[exponents] = len(singlet_paths)
        for basis_index, history in enumerate(singlet_paths, start=1):
            channels.append(
                {
                    "total_degree": sum(exponents),
                    "multidegree": list(exponents),
                    "label": row["label"],
                    "basis_index": basis_index,
                    "coupling_steps": history,
                }
            )

    totals = {
        degree: sum(1 for channel in channels if channel["total_degree"] == degree)
        for degree in (2, 3, 4)
    }
    expected_totals = {
        2: count_result["totals"]["quadratic"],  # type: ignore[index]
        3: count_result["totals"]["cubic"],  # type: ignore[index]
        4: count_result["totals"]["quartic"],  # type: ignore[index]
    }
    checks = {
        "channel_totals_match_molien": totals == expected_totals,
        "every_multidegree_matches_molien": all(
            counts_by_multidegree[tuple(row["multidegree"])] == int(row["singlet_multiplicity"])
            for row in count_result["rows"]  # type: ignore[index]
        ),
        "quadratic_channels": totals[2],
        "cubic_channels": totals[3],
        "quartic_channels": totals[4],
        "total_channels": len(channels),
    }
    return {
        "schema_version": "1.0.0",
        "project": "TP-03 Pati-Salam benchmark",
        "basis_type": "left-associated irreducible coupling-channel basis",
        "irrep_label_convention": "[a,b,c];m_L;m_R, with SU(2) dimension m+1",
        "clebsch_convention": (
            "Each channel denotes one orthonormal intertwiner after a standard CG phase convention "
            "is chosen. Component tensors are intentionally not duplicated in the repository."
        ),
        "factor_symmetric_power_decompositions": {
            field: {
                str(degree): [
                    {"irrep": list(label), "multiplicity": multiplicity}
                    for label, multiplicity in decompositions
                ]
                for degree, decompositions in degree_map.items()
            }
            for field, degree_map in factor_decompositions.items()
        },
        "channels": channels,
        "checks": checks,
        "all_pass": all(
            value for key, value in checks.items() if isinstance(value, bool)
        ),
    }


def write_outputs(root: Path, result: Mapping[str, object]) -> None:
    results_dir = root / "results"
    results_dir.mkdir(parents=True, exist_ok=True)
    (results_dir / "invariant_coupling_basis.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8"
    )

    with (root / "invariant_coupling_basis.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(
            [
                "total_degree",
                *FIELD_NAMES,
                "basis_index",
                "label",
                "coupling_path",
            ]
        )
        for channel in result["channels"]:  # type: ignore[index]
            assert isinstance(channel, dict)
            exponents = channel["multidegree"]
            assert isinstance(exponents, list)
            steps = channel["coupling_steps"]
            assert isinstance(steps, list)
            path_text = " | ".join(
                f"{step['field']}^Sym{step['symmetric_degree']}:"
                f"{label_text(tuple(step['factor_irrep']))}[{step['factor_copy']}] + "
                f"{label_text(tuple(step['input_irrep']))} -> "
                f"{label_text(tuple(step['output_irrep']))}[{step['cg_copy']}]"
                for step in steps
            )
            writer.writerow(
                [
                    channel["total_degree"],
                    *exponents,
                    channel["basis_index"],
                    channel["label"],
                    path_text,
                ]
            )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="TP-03 project root",
    )
    args = parser.parse_args()
    result = build_basis()
    write_outputs(args.root.resolve(), result)
    print(json.dumps(result["checks"], indent=2))
    if not result["all_pass"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
